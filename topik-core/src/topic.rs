use std::marker::PhantomData;

use crate::encoding::Encoding;
use crate::error::TopikError;
use crate::subscribe::SubscribeBuilder;
use crate::syntax::TopicSyntax;
use bytes::Bytes;

pub mod private {
    pub trait Sealed {}
}

pub trait Topic {
    /// The payload type carried by this topic.
    type Payload;

    /// The encoding used to serialize and deserialize the payload.
    type Encoding: Encoding<Self::Payload>;

    /// Human readable name for this topic type, derived from the struct name.
    ///
    /// ```ignore
    /// assert_eq!(SensorReading::NAME, "SensorReading");
    /// ```
    const NAME: &'static str;
}

/// Internal trait used by backends to render and parse topic strings.
///
/// Sealed: cannot be implemented outside of topik. The derive macro
/// generates all implementations.
#[doc(hidden)]
pub trait TopicWire: Topic + private::Sealed {
    type Key;
    type SubscribeBuilder: SubscribeBuilder + Send + 'static;

    fn render<S: TopicSyntax>(&self) -> String;

    fn parse<S: TopicSyntax>(topic: &str) -> Result<Self::Key, TopikError>;

    fn wildcard_pattern<S: TopicSyntax>() -> String;

    /// Reconstruct the full topic struct from a parsed key and decoded payload.
    ///
    /// Called by backends after both parsing and payload decoding succeed.
    fn from_key_and_payload(key: Self::Key, payload: Self::Payload) -> Self;

    /// Returns a reference to the payload field.
    /// Generated by the derive macro from the `#[payload]` field.
    fn payload(&self) -> &Self::Payload;

    /// Returns a subscribe builder for this topic type.
    /// All dynamic segments start as wildcards.
    fn subscribe_builder() -> Self::SubscribeBuilder;

    fn decode_payload(bytes: Bytes) -> Result<Self::Payload, TopikError>
    where
        Self: Sized,
    {
        Self::Encoding::decode(bytes)
    }

    fn display<S: TopicSyntax>(&self) -> TopicDisplay<'_, Self, S>
    where
        Self: Sized,
    {
        TopicDisplay {
            topic: self,
            protocol: PhantomData,
        }
    }
}

pub struct TopicDisplay<'a, M: TopicWire, S: TopicSyntax> {
    topic: &'a M,
    protocol: PhantomData<S>,
}

impl<'a, M: TopicWire, S: TopicSyntax> std::fmt::Display for TopicDisplay<'a, M, S> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.topic.render::<S>())
    }
}

/// Trait for enums that group multiple topic types for unified subscription.
pub trait TopicEnum: Sized + Send + 'static {
    /// Returns all wildcard subscription patterns this enum covers.
    fn patterns<S: TopicSyntax>() -> Vec<String>;

    /// Parse a raw topic string and payload bytes into a typed enum variant.
    fn try_from_raw<S: TopicSyntax>(topic: &str, payload: &[u8]) -> Result<Self, TopikError>;
}
